"""Freeze ICU collation for BobTV's finite translated country vocabulary.

Usage (macOS ICU): python generate_country_collation.py --unihan Unihan-17.0.0.zip
Runtime clients share these tables, avoiding OS-specific collation differences.
"""
import argparse
import ctypes
import hashlib
import json
from pathlib import Path
import re
import unicodedata
import zipfile

ROOT=Path(__file__).resolve().parents[2]
# Explicit country-name reading prefixes. Never read Japanese kanji as Mandarin.
JA_READINGS={'東':'ひがし','中国':'ちゅうごく','中央':'ちゅうおう','疑似':'ぎじ',
 '北朝鮮':'きたちょうせん','北':'きた','南極':'なんきょく','南':'みなみ',
 '台湾':'たいわん','日本':'にほん','欧州連合':'おうしゅうれんごう','仏領':'ふつりょう',
 '合衆国領有小離島':'がっしゅうこくりょうゆうしょうりとう','米領':'べいりょう',
 '国際連合':'こくさいれんごう','英領':'えいりょう','西':'にし','赤道':'せきどう',
 '韓国':'かんこく','香港':'ほんこん'}
JA_ROWS={'あ':'あいうえおぁぃぅぇぉ','か':'かきくけこ','さ':'さしすせそ','た':'たちつてとっ',
 'な':'なにぬねの','は':'はひふへほ','ま':'まみむめも','や':'やゆよゃゅょ','ら':'らりるれろ','わ':'わをんゎ'}
LIGATURES={'Œ':'OE','œ':'oe','Æ':'AE','æ':'ae','Ø':'O','ø':'o','Ł':'L','ł':'l','Ð':'D','ð':'d','Þ':'TH','þ':'th','ß':'ss'}

def fold(value):
    return ''.join(c for c in unicodedata.normalize('NFKD',''.join(LIGATURES.get(c,c) for c in value)) if not unicodedata.combining(c)).lower()

def ja_reading(value):
    for prefix in sorted(JA_READINGS,key=len,reverse=True):
        if value.startswith(prefix):return JA_READINGS[prefix]+value[len(prefix):]
    if re.match('[\u4e00-\u9fff]',value):raise ValueError('unreviewed Japanese reading: '+value)
    return value

def main():
    p=argparse.ArgumentParser();p.add_argument('--unihan',type=Path,required=True);a=p.parse_args()
    with zipfile.ZipFile(a.unihan) as z:
        strokes={chr(int(row[0][2:],16)):int(row[2].split()[-1]) for line in z.read('Unihan_IRGSources.txt').decode().splitlines()
                 if not line.startswith('#') and '\tkTotalStrokes\t' in line for row in [line.split('\t')]}
    legacy=(ROOT/'lib/data/services/country_name_index.dart').read_text()
    initials={c:k for k,cs in re.findall(r"'([A-Z])': '([^']+)'",legacy) for c in cs}
    lib=ctypes.CDLL('/usr/lib/libicucore.A.dylib')
    lib.ucol_open.argtypes=[ctypes.c_char_p,ctypes.POINTER(ctypes.c_int32)];lib.ucol_open.restype=ctypes.c_void_p
    lib.ucol_getSortKey.argtypes=[ctypes.c_void_p,ctypes.POINTER(ctypes.c_uint16),ctypes.c_int32,ctypes.POINTER(ctypes.c_uint8),ctypes.c_int32];lib.ucol_getSortKey.restype=ctypes.c_int32
    lib.ucol_close.argtypes=[ctypes.c_void_p]
    version=(ctypes.c_uint8*4)();lib.u_getVersion(version)
    tables={};folds={}
    for tag,locale in [('en','en'),('zh-CN','zh_CN@collation=pinyin'),('zh-TW','zh_TW@collation=stroke'),('ja','ja'),('fr','fr'),('es','es'),('ko','ko')]:
        error=ctypes.c_int32(0);collator=lib.ucol_open(locale.encode(),ctypes.byref(error));assert collator and error.value<=0
        names={k[8:]:v for k,v in json.loads((ROOT/'assets/i18n'/f'{tag}.json').read_text()).items() if k.startswith('country:')}
        def key(value):
            data=value.encode('utf-16-le');buffer=(ctypes.c_uint16*(len(data)//2)).from_buffer_copy(data);out=(ctypes.c_uint8*4096)();size=lib.ucol_getSortKey(collator,buffer,len(buffer),out,len(out));assert size<=len(out);return bytes(out[:size])
        rows=[]
        for source,label in names.items():
            reading=ja_reading(label) if tag=='ja' else '比鲁' if tag=='zh-CN' and label=='秘鲁' else label
            first=label[0]
            if source=='未识别地区':initial='#'
            elif tag=='zh-CN':initial='B' if label=='秘鲁' else initials.get(first,'#')
            elif tag=='zh-TW':
                assert first in strokes,(label,first)
                initial=str(strokes[first])+'畫'
            elif tag=='ja':
                first=unicodedata.normalize('NFKD',reading)[0];first=chr(ord(first)-0x60) if '\u30a1'<=first<='\u30f6' else first
                initial=next((k for k,v in JA_ROWS.items() if first in v),'#')
            elif tag=='ko' and '\uac00'<=first<='\ud7a3':initial='ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ'[(ord(first)-0xac00)//588]
            else:initial=fold(first).upper()[:1];initial=initial if re.fullmatch('[A-Z]',initial) else '#'
            rows.append((source,label,key(reading),initial))
            for c in label:
                if c.isascii():continue
                f=fold(c)
                if f!=c.lower():folds[c]=f
        rows.sort(key=lambda r:(r[0]=='未识别地区',r[2],r[0]))
        tables[tag]={r[1]:(i,r[3],r[0]) for i,r in enumerate(rows)}
        lib.ucol_close(collator)
    q=lambda s:json.dumps(s,ensure_ascii=False)
    output=['// Generated by tools/catalog/generate_country_collation.py. Do not edit.',
            '// ICU '+'.'.join(map(str,version))+', Unicode CLDR country labels; Unihan 17.0.0 stroke counts.',
            'const countryLocaleCollation = <String, Map<String, (int, String, String)>>{']
    for tag,rows in tables.items():
        output.append('  '+q(tag)+': {')
        for label,(rank,initial,source) in rows.items():output.append(f'    {q(label)}: ({rank}, {q(initial)}, {q(source)}),')
        output.append('  },')
    output+=['};','const countrySearchFolds = <String, String>{']+[f'  {q(k)}: {q(v)},' for k,v in sorted({**LIGATURES,**folds}.items())]+['};','']
    (ROOT/'lib/data/services/country_collation_data.dart').write_text('\n'.join(output))
    metadata={'icuVersion':list(version),'unihanVersion':'17.0.0','unihanSha256':hashlib.sha256(a.unihan.read_bytes()).hexdigest(),'locales':{k:len(v) for k,v in tables.items()},'specification':'https://unicode.org/reports/tr35/tr35-collation.html','scope':'finite country vocabulary only; Japanese reviewed reading prefixes; runtime offline'}
    (ROOT/'tools/catalog/country_collation_provenance.json').write_text(json.dumps(metadata,indent=2)+'\n')
    print(json.dumps(metadata))

if __name__=='__main__':main()
