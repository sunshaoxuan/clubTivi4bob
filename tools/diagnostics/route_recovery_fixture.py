"""Isolated native acceptance backend. Never opens the production database.

Run with BOBTV_DATA_DIR pointing at a new QA directory, PYTHONPATH at the site,
and --assets pointing at a new /assets subdirectory. Only self-generated,
audio-free test video and its explicit grant are made publicly accessible.
"""
import argparse
import asyncio
import json
import os
from pathlib import Path
import subprocess
import time

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--assets', type=Path, required=True)
parser.add_argument('--public-prefix', required=True)
parser.add_argument('--port', type=int, default=18371)
args = parser.parse_args()
root = Path(os.environ['BOBTV_DATA_DIR']).resolve()
if root.exists() or args.assets.exists() or 'acceptance' not in str(root):
    raise SystemExit('A new explicitly named acceptance directory is required')
root.mkdir(parents=True)
args.assets.mkdir(parents=True)
decoder = os.environ['BOBTV_ROUTE_DECODER']
subprocess.run([decoder, '-v', 'error', '-f', 'lavfi', '-i',
    'testsrc2=size=320x240:rate=15', '-t', '240', '-an', '-c:v', 'mpeg2video',
    '-b:v', '220k', '-g', '30', '-f', 'hls', '-hls_time', '2',
    '-hls_list_size', '0', '-hls_segment_filename', str(args.assets / 'segment%03d.ts'),
    str(args.assets / 'video.m3u8')], check=True, timeout=120)

from fastapi import FastAPI
import uvicorn
import channel_catalog
import catalog_inventory
import channel_route_recovery as recovery
import route_recovery_search as search
import server_jobs
from publish_channel_catalog import publish

prefix = args.public_prefix.rstrip('/')
channels, profiles = [], []
categories = [dict(id='cn', parentId=None, name='中国', sortOrder=0),
              dict(id='digital', parentId='cn', name='数字', sortOrder=0)]
for platform in ('mac', 'windows'):
    for index, role in enumerate(('recover', 'cancel', 'healthy')):
        key = platform + '-' + role
        name = 'QA ' + key
        playlist = args.assets / (key + '.m3u8')
        playlist.write_bytes((args.assets / 'video.m3u8').read_bytes())
        url = prefix + '/' + key + '.m3u8'
        old = url if role == 'healthy' else prefix + '/missing-' + key + '.m3u8'
        channels.append(dict(id=key, name=name, categoryId='digital', countryCode='CN',
            regionCode=None, epgId=None, logoUrl=None, sortOrder=len(channels), routes=[
            dict(id=key+'-old', url=old, source='BobTV owned synthetic acceptance fixture',
                 lastPlayableAt=None, healthScore=0.5)]))
        source = prefix + '/' + key + '.m3u'
        (args.assets / (key + '.m3u')).write_text(
            '#EXTM3U\n#EXTINF:-1 tvg-country="CN",' + name + '\n' + url + '\n')
        profiles.append(dict(channelId=key, identityVerified=True, publicationAllowed=True,
            operator='BobTV synthetic acceptance fixture', countryCode='CN', channelNumber=str(index),
            language='no speech', feedVariant='synthetic '+key, broadcastType='television',
            identityEvidenceUrls=[prefix+'/grant.txt'], authorizationEvidenceUrls=[prefix+'/grant.txt'],
            approvedDocuments=[source], mediaHosts=['bobtv.briconbric.com']))
grant = ('Owned synthetic test pattern generated by BobTV for acceptance testing. '
         'No broadcaster programme is used. Copying and playback of these fixture files '
         'is authorized. All channels are fictional test identities. No audio track.\n')
(args.assets / 'grant.txt').write_text(grant)
payload = dict(schemaVersion=1, version='qa-initial', categories=categories, channels=channels)
publish(payload, root)
for profile, channel in zip(profiles, channels):
    profile['metadataHash'] = recovery.identity(payload, channel, include_routes=False)
profile_path = root / 'profiles.json'
profile_path.write_text(json.dumps(dict(schemaVersion=1, channels=profiles)))
catalog_inventory.ingest([dict(name=c['name'], url=c['routes'][0]['url'],
    group='中国 / 数字', source='QA fixture', blocked=False, playableAt=None)
    for c in channels], 'a'*64, root)
allowed = {p['approvedDocuments'][0] for p in profiles}

def fixture_reader(url, **kwargs):
    if url not in allowed:
        raise ValueError('fixture_search_external_disabled')
    return search.read_public(url, **kwargs)

def discover(channel, profile, directory):
    return search.search_channel(channel, profile, directory, reader=fixture_reader)

async def worker():
    while True:
        await asyncio.sleep(2)
        with server_jobs.database(root) as conn:
            pending = conn.execute("SELECT min(created) FROM jobs WHERE kind='recover' AND state='queued'").fetchone()[0]
        if pending and time.time() - pending >= 15:
            result = await asyncio.to_thread(recovery.run, root, profile_path=profile_path,
                                             search=discover, limit=1)
            if result.get('processed'):
                print(json.dumps(result), flush=True)

app = FastAPI()
app.include_router(channel_catalog.router)
app.include_router(catalog_inventory.router)
app.include_router(server_jobs.router)

@app.on_event('startup')
async def start():
    asyncio.create_task(worker())

uvicorn.run(app, host='127.0.0.1', port=args.port, access_log=False)
